def section(sid):
    m = re.search(r'      <section class="section" id="%s".*?</section>\n' % sid, HOME, re.S)
    return m.group(0)


def head_part():
    """Всё от <body> до </header> с главной, без внутренних якорей главной."""
    m = re.search(r'<body>.*?</header>\n', HOME, re.S)
    return m.group(0)


def foot_part():
    m = re.search(r'    <footer.*', HOME, re.S)
    return m.group(0)


def faq_ld(items):
    clean = lambda t: re.sub(r'<[^>]+>', '', t)
    return {"@type": "FAQPage", "mainEntity": [
        {"@type": "Question", "name": clean(q), "acceptedAnswer": {"@type": "Answer", "text": clean(a)}} for q, a in items]}


def crumbs_ld(items):
    out = []
    for i, (name, url) in enumerate(items, 1):
        e = {"@type": "ListItem", "position": i, "name": name}
        if url:
            e["item"] = BASE + url
        out.append(e)
    return {"@type": "BreadcrumbList", "itemListElement": out}


def crumbs_html(items):
    parts = []
    for name, url in items:
        parts.append(f'<a href="{url}">{name}</a>' if url else f'<span>{name}</span>')
    return '    <nav class="crumbs" aria-label="Хлебные крошки">' + '<span>/</span>'.join(parts) + '</nav>\n'


